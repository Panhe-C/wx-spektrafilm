#!/usr/bin/env python3
"""Embed the canonical GLSL files in a committed WeChat CommonJS module."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    "lutVertex": ROOT / "shaders" / "lut.vert.glsl",
    "lutFragment": ROOT / "shaders" / "lut.frag.glsl",
    "haloFragment": ROOT / "shaders" / "halo.frag.glsl",
}
DESTINATION = ROOT / "utils" / "shaders.js"


def generate() -> str:
    values = {name: path.read_text(encoding="utf-8") for name, path in SOURCES.items()}
    lines = [
        "// AUTO-GENERATED by tools/embed_shaders.py; do not edit.",
        "// Canonical sources: shaders/lut.vert.glsl and shaders/lut.frag.glsl.",
        "module.exports = {",
    ]
    for name, source in values.items():
        lines.append(f"  {name}: {json.dumps(source, ensure_ascii=False)},")
    lines.extend(["};", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated module is stale")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_text(encoding="utf-8") != generated:
            print(f"Stale or missing {DESTINATION.relative_to(ROOT)}; run tools/embed_shaders.py")
            return 1
        print(f"Shader embedding is current: {DESTINATION.relative_to(ROOT)}")
        return 0
    DESTINATION.parent.mkdir(parents=True, exist_ok=True)
    DESTINATION.write_text(generated, encoding="utf-8")
    print(f"Embedded {len(SOURCES)} shaders in {DESTINATION.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
